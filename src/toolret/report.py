"""Markdown results page built from the benchmark JSON files."""

from __future__ import annotations

import json
from pathlib import Path


def table(runs: list[dict]) -> str:
    lines = [
        "| Retriever | Test split | n | R@1 | R@3 | R@5 | R@10 | MRR | Macro R@1 | ms/query |",
        "|---|---|---|---|---|---|---|---|---|---|",
    ]
    for r in runs:
        lines.append(
            f"| {r['retriever']} | {r['split']} | {r['n']} | {r['recall@1']:.3f} | "
            f"{r['recall@3']:.3f} | {r['recall@5']:.3f} | {r['recall@10']:.3f} | "
            f"{r['mrr']:.3f} | {r['macro_recall@1']:.3f} | {r['ms_per_query']:.1f} |"
        )
    return "\n".join(lines)


def write_report(reports: Path) -> Path:
    parts = ["# Results\n", "Generated by `toolret report`.\n"]
    for name, title in (
        ("benchmark.json", "Full benchmark"),
        ("benchmark_bm25.json", "BM25 only (re-run in CI)"),
    ):
        path = reports / name
        if path.exists():
            res = json.loads(path.read_text())
            pb = res["prompt_budget"]
            parts += [
                f"## {title}\n",
                table(res["runs"]),
                "",
                f"Library: {pb['library_tools']} tools, about {pb['all_schemas_tokens_approx']:,} "
                f"tokens of schemas if all were put in the prompt, versus about "
                f"{pb['top5_schemas_tokens_approx']} tokens for the top 5 (4 characters per "
                "token estimate).\n",
            ]
    out = reports / "results.md"
    out.write_text("\n".join(parts), encoding="utf-8")
    return out
